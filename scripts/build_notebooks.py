         "",
         f"cohort = abundance.loc[mine]",
         f"cohort_meta = metadata.loc[mine].copy()",
         "cohort_meta['SLEDAI_band'] = pd.cut(",
         "    pd.to_numeric(cohort_meta.get('SLEDAI_2K'), errors='coerce'),",
         "    [-0.1, 0, 4, 8, 30], labels=['0', '1-4', '5-8', '9+'])",
