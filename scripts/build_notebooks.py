"""Generate the demo notebooks. Kept as a script so they are reproducible artifacts
rather than hand-edited JSON that drifts.

ONE NOTEBOOK PER STEP PER PARTY, numbered, run in order. No notebook is ever
re-entered. The cohort pairs (01/02, 04/05, 07/08, 10/11) are near-identical on
purpose: in a real deployment they run on different machines at different
institutions, and seeing them side by side is what makes the separation concrete.

Every notebook drives the command line, so what you read is what you would type. The
k-means equivalents live in the kmeans-py repository, one method per set of notebooks.
"""
import json
from pathlib import Path

def md(*lines):  return {"cell_type": "markdown", "metadata": {}, "source": "\n".join(lines)}
def code(*lines): return {"cell_type": "code", "execution_count": None, "metadata": {},
                          "outputs": [], "source": "\n".join(lines)}

def write(path, cells, title):
    nb = {"cells": cells, "metadata": {
            "kernelspec": {"display_name": "Python 3", "language": "python", "name": "python3"},
            "language_info": {"name": "python", "version": "3.12"}},
          "nbformat": 4, "nbformat_minor": 5}
    Path(path).write_text(json.dumps(nb, indent=1))
    print(f"wrote {path}  ({len(cells)} cells)  {title}")


